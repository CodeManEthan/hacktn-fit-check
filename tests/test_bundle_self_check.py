"""Design §2.4: a power add-on counts only when its own plate runs on the clinic's mains."""

from __future__ import annotations

from app.domain.device import DeviceFacts
from app.domain.marketplace import GeoPoint, Offer
from app.domain.provenance import Provenance, fact
from app.domain.requirement import Requirement, RequirementKind
from app.domain.result import CheckResult, CheckStatus, Outcome, Verdict
from app.matching.bundle import build_bundle
from tests.factories import facility

DONOR = Provenance.DONOR_STATED
KAYUNGA = facility(name="Kayunga", country="Uganda", mains_voltage_v=240, mains_frequency_hz=50)


def needing(kind: RequirementKind) -> Verdict:
    requirement = Requirement(kind, kind.value, "k")
    return Verdict(outcome=Outcome.WORKS_IF, results=(
        CheckResult(key="k", label="k", status=CheckStatus.MITIGABLE, detail="",
                    requirement=requirement),
    ))


def addon(id: int, low=None, high=None, hz=None, name="Add-on") -> Offer:
    dev = DeviceFacts(
        manufacturer=fact(name, DONOR), model=fact(str(id), DONOR),
        voltage_min_v=fact(low, DONOR), voltage_max_v=fact(high, DONOR),
        frequencies_hz=fact(hz, DONOR),
    )
    return Offer(donor_name=f"Donor {id}", donor_email="d@example.org", device=dev,
                 origin=GeoPoint(country="Uganda"), quantity_offered=1, id=id)


SOLLATEK = addon(1, 160, 260, [50], "Sollatek")
HOUSTON_AVR = addon(2, 110, 120, [60], "Houston AVR")
BARE = addon(3, name="Unplated")
TWO_THIRTY_ONLY = addon(4, 220, 230, [50], "230 V only")
HALF_KNOWN = addon(5, 160, 260, None, "Half known")


def test_the_three_states_for_a_stabiliser():
    stock = [SOLLATEK, HOUSTON_AVR, BARE, TWO_THIRTY_ONLY, HALF_KNOWN]
    bundle = build_bundle(needing(RequirementKind.STABILISER), KAYUNGA, lambda k, t: stock)

    (item,) = bundle.items
    assert item.offers == (SOLLATEK,)
    assert item.rejected_offers == (HOUSTON_AVR,)
    assert item.unverified_offers == (BARE, TWO_THIRTY_ONLY, HALF_KNOWN)
    assert item.available and item.total_units == 1
    assert bundle.complete


def test_a_requirement_with_only_rejected_and_unverified_stock_is_a_gap():
    bundle = build_bundle(needing(RequirementKind.BACKUP_POWER), KAYUNGA,
                          lambda k, t: [HOUSTON_AVR, BARE])

    (item,) = bundle.items
    assert not item.available
    assert item.status == "nobody has one"
    assert bundle.gaps == (item,)


def test_every_power_add_on_kind_is_self_checked():
    for kind in (RequirementKind.TRANSFORMER, RequirementKind.STABILISER,
                 RequirementKind.BACKUP_POWER, RequirementKind.DEHUMIDIFIER):
        (item,) = build_bundle(needing(kind), KAYUNGA, lambda k, t: [HOUSTON_AVR]).items
        assert item.rejected_offers == (HOUSTON_AVR,), kind


def test_consumables_and_parts_are_not_self_checked():
    for kind in (RequirementKind.CONSUMABLES, RequirementKind.SPARE_PARTS):
        (item,) = build_bundle(needing(kind), KAYUNGA, lambda k, t: [BARE, HOUSTON_AVR]).items
        assert item.offers == (BARE, HOUSTON_AVR)
        assert item.rejected_offers == () and item.unverified_offers == ()


def test_the_handover_packet_is_generated_not_searched():
    searched = []
    bundle = build_bundle(needing(RequirementKind.MANUAL), KAYUNGA,
                          lambda k, t: searched.append(k) or [])

    assert searched == []
    assert bundle.items[0].status == "generated by Fit-Check"
